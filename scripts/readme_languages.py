"""Print, check or write the README's language lists from hermeneus_engine/languages.py.

The README holds two collapsible lists between the markers below: the languages Hermeneus
listens in (Scribe v3 Live, which are also the subtitle languages) and the languages it speaks
in (Flash v2.5). Both are sorted alphabetically by English name. The names and their sources
are in hermeneus_engine/languages.py; this script only formats them.

    python scripts/readme_languages.py           # print the block
    python scripts/readme_languages.py --check   # exit 1 if README.md differs from the code
    python scripts/readme_languages.py --write   # replace the block in README.md

tests/test_readme_languages.py runs the check.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from hermeneus_engine import languages  # noqa: E402

START = "<!-- languages:start (generated by scripts/readme_languages.py; do not edit by hand) -->"
END = "<!-- languages:end -->"
README = ROOT / "README.md"


def _sort_key(name: str) -> str:
    """Alphabetical order that ignores accents, so "Māori" sorts as "Maori"."""
    plain = "".join(c for c in unicodedata.normalize("NFKD", name) if not unicodedata.combining(c))
    return plain.casefold()


def _names(codes) -> list[str]:
    return sorted((languages.display_name(c) for c in codes), key=_sort_key)


def block() -> str:
    """The README block, markers included."""
    listen = _names(languages.stt_codes())
    speak = _names(languages.tts_codes())
    return "\n".join([
        START,
        "<details>",
        f"<summary>Listens in {len(listen)} languages (subtitles in any of them)</summary>",
        "",
        ", ".join(listen) + ".",
        "",
        "</details>",
        "<details>",
        f"<summary>Speaks in {len(speak)} languages</summary>",
        "",
        ", ".join(speak) + ".",
        "",
        "</details>",
        END,
    ])


def current(text: str) -> str | None:
    """The block as it stands in ``text``, or None when the markers are missing."""
    start = text.find(START)
    end = text.find(END, start + 1) if start >= 0 else -1
    if start < 0 or end < 0:
        return None
    return text[start:end + len(END)]


def main(argv: list[str]) -> int:
    text = README.read_text(encoding="utf-8")
    if "--check" in argv:
        if current(text) == block():
            return 0
        print("README.md language lists differ from hermeneus_engine/languages.py; "
              "run python scripts/readme_languages.py --write", file=sys.stderr)
        return 1
    if "--write" in argv:
        old = current(text)
        if old is None:
            print("README.md has no language markers", file=sys.stderr)
            return 1
        README.write_text(text.replace(old, block()), encoding="utf-8")
        return 0
    print(block())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
